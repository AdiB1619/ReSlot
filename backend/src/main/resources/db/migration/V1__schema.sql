-- Pre-check for "move practicals into classrooms": per lab block, how many rooms are needed vs free classrooms.
-- Counts classrooms not used by any session, not closed, plus temporary classrooms added for the date.
CREATE FUNCTION classroom_capacity_check(p_date date, p_level text DEFAULT NULL)
RETURNS TABLE (start_time time, end_time time, needing_room integer, free_classrooms integer, shortfall integer)
LANGUAGE sql STABLE AS $$
  WITH eff AS (SELECT * FROM effective_sessions(p_date, ARRAY['APPROVED', 'PUBLISHED']::override_status[])),
  need AS (
    SELECT e.start_time AS st, e.end_time AS en, count(DISTINCT e.session_id)::integer AS n
    FROM eff e
    JOIN timetable_sessions s ON s.id = e.session_id AND s.session_type = 'LAB'
    WHERE EXISTS (SELECT 1 FROM session_groups sg JOIN student_groups g ON g.id = sg.group_id
                   WHERE sg.session_id = s.id AND (p_level IS NULL OR g.level = p_level))
    GROUP BY e.start_time, e.end_time),
  calc AS (
    SELECT n.st, n.en, n.n,
           (SELECT count(*)::integer FROM rooms r
             WHERE r.room_type = 'CLASSROOM' AND r.is_active
               AND (NOT r.is_temporary OR EXISTS (
                      SELECT 1 FROM disruptions d
                       WHERE d.kind = 'EXTRA_ROOM' AND d.room_id = r.id AND d.on_date = p_date
                         AND (d.start_time IS NULL OR (d.start_time <= n.st AND d.end_time >= n.en))))
               AND NOT EXISTS (
                      SELECT 1 FROM disruptions d
                       WHERE d.kind = 'ROOM_UNAVAILABLE' AND d.room_id = r.id AND d.on_date = p_date
                         AND (d.start_time IS NULL OR (d.start_time < n.en AND d.end_time > n.st)))
               AND NOT EXISTS (
                      SELECT 1 FROM eff x WHERE x.room_id = r.id AND x.start_time < n.en AND x.end_time > n.st)) AS free
    FROM need n)
  SELECT st, en, n, free, greatest(n - free, 0) FROM calc ORDER BY st;
$$;

