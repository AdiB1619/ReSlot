-- ReSlot schema: Computer Engineering Dept, RSCOE (single department). PostgreSQL 16.
-- Run:  createdb reslot && psql reslot -f schema.sql -f seed.sql
-- Model: master timetable (immutable per version) + date-specific disruptions and overrides.

BEGIN;

CREATE TYPE room_type       AS ENUM ('CLASSROOM', 'LAB', 'OTHER');
CREATE TYPE session_type    AS ENUM ('LECTURE', 'LAB', 'TUTORIAL', 'OTHER');
CREATE TYPE group_kind      AS ENUM ('DIVISION', 'BATCH', 'ELECTIVE');
CREATE TYPE version_status  AS ENUM ('DRAFT', 'ACTIVE', 'ARCHIVED');
CREATE TYPE disruption_kind AS ENUM ('ROOM_UNAVAILABLE', 'FACULTY_UNAVAILABLE', 'EXTRA_ROOM', 'OTHER');
CREATE TYPE override_action AS ENUM ('MOVE', 'ROOM_CHANGE', 'CANCEL');
CREATE TYPE override_status AS ENUM ('PROPOSED', 'APPROVED', 'PUBLISHED', 'REJECTED');
CREATE TYPE notify_status   AS ENUM ('PENDING', 'SENT', 'DELIVERED', 'READ', 'FAILED');

-- ---------- reference data ----------

CREATE TABLE faculty (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code          text NOT NULL UNIQUE,              -- canonical initials, e.g. 'SRP'
  full_name     text,
  email         text,
  whatsapp_e164 text CHECK (whatsapp_e164 ~ '^\+[1-9][0-9]{7,14}$'),
  is_active     boolean NOT NULL DEFAULT true
);

CREATE TABLE faculty_aliases (                     -- typos / variants seen in the PDF (NW -> NAW)
  alias      text PRIMARY KEY,
  faculty_id bigint NOT NULL REFERENCES faculty(id)
);

CREATE TABLE rooms (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code         text NOT NULL UNIQUE,               -- canonical room number, e.g. 'A-210'
  name         text NOT NULL,
  room_type    room_type NOT NULL,
  lab_code     text UNIQUE,                        -- short code used in the PDF, e.g. 'CVL'
  capacity     integer CHECK (capacity > 0),
  is_temporary boolean NOT NULL DEFAULT false,     -- extra rooms/labs added for a day
  is_active    boolean NOT NULL DEFAULT true
);

CREATE TABLE room_aliases (                        -- ML / MLL / AML all mean A-210
  alias   text PRIMARY KEY,
  room_id bigint NOT NULL REFERENCES rooms(id)
);

CREATE TABLE subjects (
  id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code text NOT NULL UNIQUE,
  name text
);

CREATE TABLE periods (                             -- the daily grid (solver time axis)
  code       text PRIMARY KEY,
  start_time time NOT NULL,
  end_time   time NOT NULL,
  label      text,
  CHECK (start_time < end_time)
);

CREATE TABLE lab_blocks (                          -- labs are booked in fixed 2-hour blocks, classrooms by 1-hour period
  code       text PRIMARY KEY,
  start_time time NOT NULL,
  end_time   time NOT NULL,
  note       text,
  CHECK (end_time - start_time = interval '2 hours')
);

-- Students. Siblings that share a non-null partition_key are disjoint (e.g. lab batches SA1/SA2/SA3).
-- Siblings with different partitions (lab batches vs elective cohorts) may share students.
CREATE TABLE student_groups (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          text NOT NULL UNIQUE,              -- 'SY-A', 'SY-A/SA1', 'TY-A/PE1-DMA/A1'
  level         text NOT NULL CHECK (level IN ('FY', 'SY', 'TY', 'BE')),
  kind          group_kind NOT NULL,
  parent_id     bigint REFERENCES student_groups(id),
  partition_key text,
  strength      integer CHECK (strength > 0),
  CHECK ((kind = 'DIVISION') = (parent_id IS NULL))
);

-- ---------- master timetable ----------

CREATE TABLE timetable_versions (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          text NOT NULL,
  academic_year text NOT NULL,
  semester      text NOT NULL,
  effective_from date NOT NULL,
  status        version_status NOT NULL DEFAULT 'DRAFT',
  source_file   text,
  source_sha256 text UNIQUE,                       -- hash of the uploaded master: identical upload = same version
  created_at    timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX one_active_version ON timetable_versions ((true)) WHERE status = 'ACTIVE';

CREATE TABLE timetable_sessions (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version_id   bigint NOT NULL REFERENCES timetable_versions(id) ON DELETE CASCADE,
  day_of_week  smallint NOT NULL CHECK (day_of_week BETWEEN 1 AND 6),   -- ISO: 1=Mon .. 6=Sat
  start_time   time NOT NULL,
  end_time     time NOT NULL,                      -- intervals are [start, end)
  subject_id   bigint NOT NULL REFERENCES subjects(id),
  room_id      bigint REFERENCES rooms(id),        -- NULL = not specified / external
  raw_room     text,                               -- room token exactly as printed in the PDF (e.g. 'ML')
  raw_faculty  text,                               -- faculty initials exactly as printed (e.g. 'NW/JVS')
  session_type session_type NOT NULL,
  is_fixed     boolean NOT NULL DEFAULT false,     -- solver must not move it (MDM, EIS, COC, Minor...)
  source_ref   text,                               -- where in the PDF it came from
  needs_review boolean NOT NULL DEFAULT false,
  review_note  text,
  CHECK (start_time < end_time)
);
CREATE INDEX idx_sessions_slot ON timetable_sessions (version_id, day_of_week, start_time);
CREATE INDEX idx_sessions_room ON timetable_sessions (version_id, day_of_week, room_id);

CREATE TABLE session_groups (                      -- one session can serve several groups (joint classes)
  session_id bigint NOT NULL REFERENCES timetable_sessions(id) ON DELETE CASCADE,
  group_id   bigint NOT NULL REFERENCES student_groups(id),
  PRIMARY KEY (session_id, group_id)
);

CREATE TABLE session_faculty (                     -- and several faculty (co-teaching)
  session_id bigint NOT NULL REFERENCES timetable_sessions(id) ON DELETE CASCADE,
  faculty_id bigint NOT NULL REFERENCES faculty(id),
  PRIMARY KEY (session_id, faculty_id)
);
CREATE INDEX idx_session_faculty_fac ON session_faculty (faculty_id);

-- ---------- date-specific operations ----------

CREATE TABLE disruptions (                         -- WHAT HAPPENED (input from admin / agent)
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind       disruption_kind NOT NULL,
  room_id    bigint REFERENCES rooms(id),
  faculty_id bigint REFERENCES faculty(id),
  on_date    date NOT NULL,
  start_time time,                                 -- NULL start/end = whole day
  end_time   time,
  reason     text,
  created_by text,
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (room_id IS NOT NULL OR faculty_id IS NOT NULL),
  CHECK ((start_time IS NULL) = (end_time IS NULL)),
  CHECK (start_time IS NULL OR start_time < end_time)
);
CREATE INDEX idx_disruptions_date ON disruptions (on_date);

CREATE TABLE room_policy_overrides (          -- date-specific rule: let practicals use other room types
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  on_date           date NOT NULL,
  level             text CHECK (level IN ('FY', 'SY', 'TY', 'BE')),   -- a whole year ...
  group_id          bigint REFERENCES student_groups(id),             -- ... or one division / batch (covers its sub-groups)
  session_type      session_type NOT NULL DEFAULT 'LAB',
  allow_room_types  room_type[] NOT NULL,                             -- e.g. {CLASSROOM}
  layout            text NOT NULL DEFAULT 'ONE_ROOM_PER_BATCH' CHECK (layout IN ('ONE_ROOM_PER_BATCH', 'MERGE_BATCHES')),
  confirmed_by      text,
  reason            text,
  created_by        text,
  created_at        timestamptz NOT NULL DEFAULT now(),
  CHECK (level IS NULL OR group_id IS NULL),                          -- both NULL = whole department
  CHECK (cardinality(allow_room_types) > 0),
  CHECK (layout = 'ONE_ROOM_PER_BATCH' OR confirmed_by IS NOT NULL)   -- merging batches always needs a named human
);

CREATE TABLE rescheduling_runs (                  -- one solver run: which master, which inputs, what came out
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version_id     bigint NOT NULL REFERENCES timetable_versions(id),
  on_date        date NOT NULL,
  inputs         jsonb NOT NULL,                  -- disruptions, extra rooms, solver settings (reproducible)
  status         text NOT NULL CHECK (status IN ('SOLVED', 'INFEASIBLE', 'FAILED')),
  moved_sessions integer,
  solve_ms       integer,
  summary        jsonb,
  created_by     text,
  created_at     timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE schedule_overrides (                  -- THE RESPONSE: one row per affected session per date
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  disruption_id   bigint REFERENCES disruptions(id),
  run_id          bigint REFERENCES rescheduling_runs(id),
  session_id      bigint NOT NULL REFERENCES timetable_sessions(id),
  on_date         date NOT NULL,
  action          override_action NOT NULL,
  orig_start_time time NOT NULL,                   -- always keep the original assignment
  orig_end_time   time NOT NULL,
  orig_room_id    bigint REFERENCES rooms(id),
  new_start_time  time,
  new_end_time    time,
  new_room_id     bigint REFERENCES rooms(id),
  reason          text,
  status          override_status NOT NULL DEFAULT 'PROPOSED',
  proposed_at     timestamptz NOT NULL DEFAULT now(),
  approved_by     text,
  approved_at     timestamptz,
  published_at    timestamptz,
  CHECK ((new_start_time IS NULL) = (new_end_time IS NULL)),
  CHECK (action <> 'MOVE' OR new_start_time IS NOT NULL),
  CHECK (action <> 'ROOM_CHANGE' OR new_room_id IS NOT NULL),
  CHECK (status NOT IN ('APPROVED', 'PUBLISHED') OR approved_by IS NOT NULL)
);
CREATE UNIQUE INDEX uq_active_override ON schedule_overrides (session_id, on_date) WHERE status <> 'REJECTED';

CREATE TABLE notification_jobs (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  override_id         bigint NOT NULL REFERENCES schedule_overrides(id),
  faculty_id          bigint REFERENCES faculty(id),
  group_id            bigint REFERENCES student_groups(id),
  message             text NOT NULL,
  dedupe_key          text NOT NULL UNIQUE,        -- e.g. 'override:42:faculty:7' -> no duplicate sends
  status              notify_status NOT NULL DEFAULT 'PENDING',
  attempts            integer NOT NULL DEFAULT 0,
  provider_message_id text,
  last_error          text,
  created_at          timestamptz NOT NULL DEFAULT now(),
  sent_at             timestamptz,
  CHECK ((faculty_id IS NULL) <> (group_id IS NULL))
);

CREATE TABLE audit_log (
  id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  at        timestamptz NOT NULL DEFAULT now(),
  actor     text NOT NULL,
  action    text NOT NULL,
  entity    text NOT NULL,
  entity_id bigint,
  detail    jsonb
);

-- ---------- student-group overlap ----------

CREATE VIEW v_group_path AS
WITH RECURSIVE t AS (
  SELECT id, ARRAY[id] AS path FROM student_groups WHERE parent_id IS NULL
  UNION ALL
  SELECT g.id, t.path || g.id FROM student_groups g JOIN t ON g.parent_id = t.id
)
SELECT id, path FROM t;

-- Can two groups contain the same student?
--  different divisions -> no; ancestor/descendant -> yes;
--  otherwise look at the two branches below the lowest common ancestor:
--  disjoint only when both branches share the same non-null partition_key.
CREATE FUNCTION groups_overlap(a bigint, b bigint) RETURNS boolean
LANGUAGE sql STABLE AS $$
  WITH p AS (
    SELECT (SELECT path FROM v_group_path WHERE id = a) AS pa,
           (SELECT path FROM v_group_path WHERE id = b) AS pb
  ), k AS (
    SELECT pa, pb,
           (SELECT max(i) FROM generate_series(1, least(cardinality(pa), cardinality(pb))) i
             WHERE pa[1:i] = pb[1:i]) AS lca
    FROM p
  )
  SELECT CASE
           WHEN lca IS NULL THEN false
           WHEN lca = cardinality(pa) OR lca = cardinality(pb) THEN true
           ELSE NOT EXISTS (
             SELECT 1 FROM student_groups x, student_groups y
             WHERE x.id = pa[lca + 1] AND y.id = pb[lca + 1]
               AND x.partition_key IS NOT NULL AND x.partition_key = y.partition_key)
         END
  FROM k;
$$;

-- ---------- readable views ----------

CREATE VIEW v_session_detail AS
SELECT s.id AS session_id, s.version_id, s.day_of_week,
       (ARRAY['Mon','Tue','Wed','Thu','Fri','Sat'])[s.day_of_week] AS day_name,
       s.start_time, s.end_time, sub.code AS subject, s.session_type, r.code AS room,
       (SELECT string_agg(g.name, ', ' ORDER BY g.name)
          FROM session_groups sg JOIN student_groups g ON g.id = sg.group_id
         WHERE sg.session_id = s.id) AS student_groups,
       (SELECT string_agg(f.code, '/' ORDER BY f.code)
          FROM session_faculty sf JOIN faculty f ON f.id = sf.faculty_id
         WHERE sf.session_id = s.id) AS faculty,
       s.is_fixed, s.needs_review, s.review_note
FROM timetable_sessions s
JOIN subjects sub ON sub.id = s.subject_id
LEFT JOIN rooms r ON r.id = s.room_id;

-- ---------- conflict detection on the master (validator input) ----------

CREATE VIEW v_room_conflicts AS
SELECT a.version_id, a.day_of_week, a.room_id, a.id AS session_a, b.id AS session_b,
       greatest(a.start_time, b.start_time) AS overlap_start,
       least(a.end_time, b.end_time)        AS overlap_end
FROM timetable_sessions a
JOIN timetable_sessions b
  ON a.version_id = b.version_id AND a.day_of_week = b.day_of_week
 AND a.room_id = b.room_id AND a.id < b.id
 AND a.start_time < b.end_time AND b.start_time < a.end_time;

CREATE VIEW v_faculty_conflicts AS
SELECT a.version_id, a.day_of_week, fa.faculty_id, a.id AS session_a, b.id AS session_b,
       greatest(a.start_time, b.start_time) AS overlap_start,
       least(a.end_time, b.end_time)        AS overlap_end
FROM session_faculty fa
JOIN session_faculty fb ON fb.faculty_id = fa.faculty_id AND fa.session_id < fb.session_id
JOIN timetable_sessions a ON a.id = fa.session_id
JOIN timetable_sessions b ON b.id = fb.session_id
 AND b.version_id = a.version_id AND b.day_of_week = a.day_of_week
 AND a.start_time < b.end_time AND b.start_time < a.end_time;

CREATE VIEW v_group_conflicts AS
SELECT DISTINCT a.version_id, a.day_of_week, a.id AS session_a, b.id AS session_b,
       ga.group_id AS group_a, gb.group_id AS group_b
FROM timetable_sessions a
JOIN timetable_sessions b
  ON b.version_id = a.version_id AND b.day_of_week = a.day_of_week AND a.id < b.id
 AND a.start_time < b.end_time AND b.start_time < a.end_time
JOIN session_groups ga ON ga.session_id = a.id
JOIN session_groups gb ON gb.session_id = b.id
WHERE groups_overlap(ga.group_id, gb.group_id);

-- ---------- the output: effective timetable for a date ----------
-- master (active version) + PUBLISHED overrides for that date.

CREATE FUNCTION effective_timetable(p_date date)
RETURNS TABLE (session_id bigint, on_date date, start_time time, end_time time, room text,
               subject text, student_groups text, faculty text, status text)
LANGUAGE sql STABLE AS $$
  SELECT d.session_id, p_date,
         coalesce(o.new_start_time, d.start_time),
         coalesce(o.new_end_time, d.end_time),
         CASE WHEN o.action = 'CANCEL' THEN NULL
              ELSE coalesce((SELECT code FROM rooms WHERE id = o.new_room_id), d.room) END,
         d.subject, d.student_groups, d.faculty,
         CASE o.action WHEN 'CANCEL' THEN 'CANCELLED'
                       WHEN 'MOVE' THEN 'RESCHEDULED'
                       WHEN 'ROOM_CHANGE' THEN 'ROOM_CHANGED'
                       ELSE 'UNCHANGED' END
  FROM v_session_detail d
  JOIN timetable_versions v ON v.id = d.version_id AND v.status = 'ACTIVE'
  LEFT JOIN schedule_overrides o
         ON o.session_id = d.session_id AND o.on_date = p_date AND o.status = 'PUBLISHED'
  WHERE d.day_of_week = extract(isodow FROM p_date)::smallint
  ORDER BY 3, 6;
$$;

-- ---------- master-first rule: the master timetable is read-only once ACTIVE ----------
-- Corrections are only possible by creating a NEW version (DRAFT -> review -> ACTIVE).

CREATE FUNCTION trg_lock_master() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
  v_id     bigint;
  v_status version_status;
  v_sess   bigint;
BEGIN
  IF TG_TABLE_NAME = 'timetable_sessions' THEN
    v_id := CASE WHEN TG_OP = 'DELETE' THEN OLD.version_id ELSE NEW.version_id END;
  ELSE
    v_sess := CASE WHEN TG_OP = 'DELETE' THEN OLD.session_id ELSE NEW.session_id END;
    SELECT version_id INTO v_id FROM timetable_sessions WHERE id = v_sess;
  END IF;
  SELECT status INTO v_status FROM timetable_versions WHERE id = v_id;
  IF v_status IS NOT NULL AND v_status <> 'DRAFT' THEN
    RAISE EXCEPTION 'master timetable version % is % and read-only; create a new version to change it', v_id, v_status;
  END IF;
  RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END $$;

CREATE TRIGGER lock_sessions BEFORE INSERT OR UPDATE OR DELETE ON timetable_sessions
  FOR EACH ROW EXECUTE FUNCTION trg_lock_master();
CREATE TRIGGER lock_session_groups BEFORE INSERT OR UPDATE OR DELETE ON session_groups
  FOR EACH ROW EXECUTE FUNCTION trg_lock_master();
CREATE TRIGGER lock_session_faculty BEFORE INSERT OR UPDATE OR DELETE ON session_faculty
  FOR EACH ROW EXECUTE FUNCTION trg_lock_master();

CREATE FUNCTION trg_version_lifecycle() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    IF OLD.status <> 'DRAFT' THEN
      RAISE EXCEPTION 'only DRAFT master versions can be deleted';
    END IF;
    RETURN OLD;
  END IF;
  IF NEW.status <> OLD.status
     AND NOT ((OLD.status = 'DRAFT' AND NEW.status = 'ACTIVE')
           OR (OLD.status = 'ACTIVE' AND NEW.status = 'ARCHIVED')) THEN
    RAISE EXCEPTION 'illegal master version transition % -> %', OLD.status, NEW.status;
  END IF;
  RETURN NEW;
END $$;

CREATE TRIGGER version_lifecycle BEFORE UPDATE OR DELETE ON timetable_versions
  FOR EACH ROW EXECUTE FUNCTION trg_version_lifecycle();

-- ---------- validator: an override must not introduce any NEW clash ----------
-- The master may contain clashes of its own. They are the accepted baseline: never edited, never hidden
-- (pre_existing = true). Only clashes created by overrides (pre_existing = false) block approval/publish.

CREATE FUNCTION effective_sessions(p_date date,
                                   p_statuses override_status[] DEFAULT ARRAY['PUBLISHED']::override_status[])
RETURNS TABLE (session_id bigint, start_time time, end_time time, room_id bigint, action override_action)
LANGUAGE sql STABLE AS $$
  SELECT s.id,
         coalesce(o.new_start_time, s.start_time),
         coalesce(o.new_end_time, s.end_time),
         coalesce(o.new_room_id, s.room_id),
         o.action
  FROM timetable_sessions s
  JOIN timetable_versions v ON v.id = s.version_id AND v.status = 'ACTIVE'
  LEFT JOIN schedule_overrides o
         ON o.session_id = s.id AND o.on_date = p_date AND o.status = ANY (p_statuses)
  WHERE s.day_of_week = extract(isodow FROM p_date)::smallint
    AND o.action IS DISTINCT FROM 'CANCEL';          -- cancelled sessions do not occur
$$;

CREATE FUNCTION effective_conflicts(p_date date,
                                    p_statuses override_status[] DEFAULT ARRAY['PUBLISHED']::override_status[])
RETURNS TABLE (kind text, session_a bigint, session_b bigint, detail text, pre_existing boolean)
LANGUAGE sql STABLE AS $$
  WITH e AS (SELECT * FROM effective_sessions(p_date, p_statuses)),
  pairs AS (
    SELECT a.session_id AS sa, b.session_id AS sb, a.room_id AS ra, b.room_id AS rb,
           a.action AS aa, b.action AS ab
    FROM e a JOIN e b ON a.session_id < b.session_id
                     AND a.start_time < b.end_time AND b.start_time < a.end_time
  )
  SELECT 'ROOM'::text, sa, sb, (SELECT code FROM rooms WHERE id = ra), (aa IS NULL AND ab IS NULL)
  FROM pairs WHERE ra IS NOT NULL AND ra = rb
  UNION ALL
  SELECT 'FACULTY', p.sa, p.sb, f.code, (p.aa IS DISTINCT FROM 'MOVE' AND p.ab IS DISTINCT FROM 'MOVE')
  FROM pairs p
  JOIN session_faculty fa ON fa.session_id = p.sa
  JOIN session_faculty fb ON fb.session_id = p.sb AND fb.faculty_id = fa.faculty_id
  JOIN faculty f ON f.id = fa.faculty_id
  UNION ALL
  SELECT DISTINCT 'GROUP', p.sa, p.sb, ga.group_id || '/' || gb.group_id,
         (p.aa IS DISTINCT FROM 'MOVE' AND p.ab IS DISTINCT FROM 'MOVE')
  FROM pairs p
  JOIN session_groups ga ON ga.session_id = p.sa
  JOIN session_groups gb ON gb.session_id = p.sb
  WHERE groups_overlap(ga.group_id, gb.group_id);
$$;
-- Blast radius: everything a plan changes, across ALL divisions and years (drives the review screen and the messages).
CREATE FUNCTION blast_radius(p_date date,
                             p_statuses override_status[] DEFAULT ARRAY['PROPOSED', 'APPROVED', 'PUBLISHED']::override_status[])
RETURNS TABLE (session_id bigint, action override_action, orig_start time, orig_end time, orig_room text,
               new_start time, new_end time, new_room text, divisions text, student_groups text, faculty text)
LANGUAGE sql STABLE AS $$
  SELECT o.session_id, o.action, o.orig_start_time, o.orig_end_time, ro.code,
         coalesce(o.new_start_time, o.orig_start_time), coalesce(o.new_end_time, o.orig_end_time),
         CASE WHEN o.action = 'CANCEL' THEN NULL ELSE coalesce(rn.code, ro.code) END,
         (SELECT string_agg(DISTINCT split_part(g.name, '/', 1), ', ' ORDER BY split_part(g.name, '/', 1))
            FROM session_groups sg JOIN student_groups g ON g.id = sg.group_id
           WHERE sg.session_id = o.session_id),
         d.student_groups, d.faculty
  FROM schedule_overrides o
  JOIN v_session_detail d ON d.session_id = o.session_id
  LEFT JOIN rooms ro ON ro.id = o.orig_room_id
  LEFT JOIN rooms rn ON rn.id = o.new_room_id
  WHERE o.on_date = p_date AND o.status = ANY (p_statuses)
  ORDER BY o.orig_start_time, o.session_id;
$$;

