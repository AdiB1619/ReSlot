-- V3: Identity tables (users, roles, refresh_tokens)
-- These are managed by Spring Data JPA but the initial structure is set up here

CREATE TABLE IF NOT EXISTS users (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email                text NOT NULL UNIQUE,
    password_hash        text NOT NULL,
    role                 text NOT NULL CHECK (role IN ('COORDINATOR','HOD','FACULTY','STUDENT','ADMIN')),
    full_name            text NOT NULL,
    active               boolean NOT NULL DEFAULT true,
    must_change_password boolean NOT NULL DEFAULT false,
    locked_until         timestamptz,
    failed_login_attempts int NOT NULL DEFAULT 0,
    created_at           timestamptz NOT NULL DEFAULT now(),
    updated_at           timestamptz
);

CREATE TABLE IF NOT EXISTS refresh_tokens (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token_hash text NOT NULL UNIQUE,
    family     text NOT NULL,
    expires_at timestamptz NOT NULL,
    revoked    boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_refresh_family ON refresh_tokens (family);
CREATE INDEX IF NOT EXISTS idx_refresh_user ON refresh_tokens (user_id);

-- V3 also: review decisions and imports tables
CREATE TABLE IF NOT EXISTS review_decisions (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_key  text NOT NULL UNIQUE,
    decision    text NOT NULL,
    note        text,
    decided_by  text,
    decided_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS imports (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sha256     text NOT NULL UNIQUE,
    filename   text NOT NULL,
    status     text NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','PARSING','REVIEW','ACTIVATING','ACTIVE','FAILED')),
    created_by text,
    created_at timestamptz NOT NULL DEFAULT now(),
    version_id bigint REFERENCES timetable_versions(id)
);

CREATE TABLE IF NOT EXISTS import_rows (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    import_id   bigint NOT NULL REFERENCES imports(id) ON DELETE CASCADE,
    source_ref  text,
    status      text NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','RESOLVED','ACCEPTED','SKIPPED')),
    payload     jsonb NOT NULL DEFAULT '{}',
    flag        text,
    resolution  jsonb,
    source_page integer,
    source_bbox jsonb
);

-- Disruptions table (may already exist from V2 but ensure it's here for JPA)
CREATE TABLE IF NOT EXISTS room_policy_overrides (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope_level   text,
    scope_div_id  bigint REFERENCES student_groups(id),
    scope_batch_id bigint REFERENCES student_groups(id),
    on_date       date NOT NULL,
    allow_room_types text[] NOT NULL DEFAULT '{}',
    layout        text NOT NULL DEFAULT 'ONE_ROOM_PER_BATCH',
    reason        text,
    confirmed_by  text,
    created_by    text,
    created_at    timestamptz NOT NULL DEFAULT now(),
    deleted       boolean NOT NULL DEFAULT false
);
